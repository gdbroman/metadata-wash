import Foundation

/// Rules for recognizing AI-generation and provenance metadata.
nonisolated enum AISignatures {
    /// Text-chunk / metadata keys that on their own carry generation data.
    static let generationKeys: Set<String> = [
        "parameters", "prompt", "negative_prompt", "negativeprompt", "workflow", "comfyui", "sd-metadata",
        "invokeai_metadata", "invokeai_graph", "generation_data", "generationdata", "ai_metadata", "dream",
        "sd:prompt", "sd:negative_prompt", "sd:seed", "sd:steps", "sd:sampler", "sd:cfg_scale", "sd:model_hash",
        "fooocus_scheme", "hf-job-id", "aigc", "generation parameters", "lora", "loras", "civitai resources",
        "aisystemused", "aisystemversionused", "aipromptinformation", "aipromptwritername",
    ]

    /// IPTC Digital Source Type values meaning "made with generative AI".
    /// Bare `algorithmicMedia` (procedural, not trained) is intentionally excluded.
    static let aiDigitalSourceTypes = ["trainedAlgorithmicMedia", "compositeWithTrainedAlgorithmicMedia", "compositeSynthetic"]

    /// China TC260 mandatory AIGC labeling markers.
    static let aigcMarkers = ["tc260.org.cn/ns/AIGC", "TC260:AIGC"]

    /// Known generator / AI product names. Matched as whole words and only in
    /// generator-bearing fields to avoid false positives on ordinary text.
    static let generatorTokens: [String] = [
        "ChatGPT", "DALL-E", "DALL·E", "DALLE", "gpt-image", "OpenAI", "Sora", "Midjourney", "Stable Diffusion",
        "stable-diffusion", "StableDiffusion", "SDXL", "SD3", "FLUX", "FLUX.1", "Black Forest Labs", "DreamStudio",
        "ComfyUI", "AUTOMATIC1111", "InvokeAI", "Fooocus", "NovelAI", "Leonardo AI", "Leonardo.Ai",
        "Ideogram", "Craiyon", "NightCafe", "TensorArt", "Recraft", "Clipdrop", "DeepAI", "Bing Image Creator",
        "Image Creator", "Microsoft Designer", "Adobe Firefly", "Firefly", "Gemini", "Imagen", "Nano Banana", "Veo",
        "Google AI", "Grok", "xAI", "Kling", "Kuaishou", "Runway", "Gen-3", "Gen-4", "Luma AI", "lumalabs",
        "Dream Machine", "Pika", "Hailuo", "MiniMax", "Hunyuan", "Doubao", "Dreamina", "Jimeng", "Seedream",
        "Seedance", "Qwen", "Wan2", "Higgsfield", "Krea", "Playground AI", "reve.com", "fal-ai", "fal.ai",
        "Freepik AI", "Canva AI", "Magic Media", "Image Playground", "Apple Photos Clean Up",
        "Generative Fill", "Generative Expand", "Galaxy AI", "Aphrodite AI", "Synthesia", "HeyGen",
    ]

    /// Phrases that disclose AI generation in free text fields.
    static let disclosurePhrases = [
        "made with ai", "made with google ai", "generated with ai", "generated by ai", "ai generated",
        "ai-generated", "created with ai", "edited with ai", "generated using ai", "synthid", "genaitype",
        "aigc", "photoeditor_re_edit_data",
    ]

    /// Fields that typically name the producing software or describe the content.
    static let generatorBearingNames: Set<String> = [
        "software", "creatortool", "make", "model", "artist", "author", "creator", "encoder", "encodedby",
        "encodingtool", "writingapp", "muxingapp", "imagedescription", "description", "comment", "usercomment",
        "xpcomment", "title", "source", "credit", "creditline", "historysoftwareagent", "softwareagent",
        "producer", "handlerdescription", "compressorname", "contentcreator", "generator", "claimgenerator",
        "aisystemused", "caption-abstract", "captionwriter", "displayname", "information", "originatingprogram",
    ]

    /// Patterns found in Stable Diffusion / ComfyUI / InvokeAI parameter dumps.
    static let parameterPatterns: [NSRegularExpression] = [
        #"\bSteps:\s*\d+"#, #"\bSampler:\s*\S"#, #"\bCFG scale:\s*[\d.]"#, #"\bNegative prompt:"#,
        #"\bModel hash:\s*[0-9a-f]"#, #"\bDenoising strength:"#, #""class_type"\s*:"#, #""ckpt_name"\s*:"#,
        #""sampler_name"\s*:"#, #""(?:cfg|cfg_scale|guidance_scale)"\s*:\s*[\d.]"#, #""negative_prompt"\s*:"#,
        #"\bLora hashes:"#, #""uc"\s*:\s*""#, #""noise_schedule"\s*:"#,
    ].compactMap { try? NSRegularExpression(pattern: $0, options: [.caseInsensitive]) }

    private static let generatorRegex: NSRegularExpression? = {
        let alternatives = generatorTokens
            .sorted { $0.count > $1.count }
            .map { NSRegularExpression.escapedPattern(for: $0) }
            .joined(separator: "|")
        return try? NSRegularExpression(pattern: "(?<![A-Za-z0-9])(\(alternatives))(?![A-Za-z0-9])", options: [.caseInsensitive])
    }()

    /// Byte markers for C2PA / JUMBF data in raw container payloads.
    static let c2paByteMarkers: [Data] = ["c2pa", "jumb", "c2ma", "c2cl", "contentauth", "contentcredentials"].map { Data($0.utf8) }

    /// UUID of the C2PA ContentProvenanceBox in ISO BMFF files (MP4, MOV, HEIF, AVIF).
    static let c2paBMFFUUID: [UInt8] = [0xD8, 0xFE, 0xC3, 0xD6, 0x1B, 0x0E, 0x48, 0x3C, 0x92, 0x97, 0x58, 0x28, 0x87, 0x7E, 0xC4, 0x81]
    /// UUID of the XMP box in ISO BMFF files.
    static let xmpBMFFUUID: [UInt8] = [0xBE, 0x7A, 0xCF, 0xCB, 0x97, 0xA9, 0x42, 0xE8, 0x9C, 0x71, 0x99, 0x94, 0x91, 0xE3, 0xAF, 0xAC]

    /// C2PA manifest repositories that can restore stripped credentials from the cloud.
    static let cloudManifestHosts = ["cai-manifests.adobe.com"]

    /// Normalizes an engine tag name for set lookups ("XPComment" → "xpcomment").
    static func normalizedKey(_ name: String) -> String {
        name.lowercased().replacingOccurrences(of: " ", with: "")
    }

    /// Returns a reason when a metadata entry indicates AI generation, or nil.
    static func aiReason(name: String, value: String) -> String? {
        let key = name.lowercased()
        let compactKey = normalizedKey(name)
        if generationKeys.contains(key) || generationKeys.contains(compactKey) {
            return "“\(name)” is a generation-data field"
        }
        if key.contains("digitalsourcetype") || key.contains("digital source type"),
           aiDigitalSourceTypes.contains(where: { value.localizedCaseInsensitiveContains($0) }) {
            return "IPTC digital source type marks the media as AI-generated"
        }
        if let marker = aigcMarkers.first(where: { value.localizedCaseInsensitiveContains($0) || name.localizedCaseInsensitiveContains($0) }) {
            return "China TC260 AIGC label (\(marker))"
        }
        let probe = value.count > 200_000 ? String(value.prefix(200_000)) : value
        let range = NSRange(probe.startIndex..., in: probe)
        if parameterPatterns.contains(where: { $0.firstMatch(in: probe, range: range) != nil }) {
            return "Contains image-generation parameters"
        }
        let lowered = probe.lowercased()
        if let phrase = disclosurePhrases.first(where: { lowered.contains($0) }) {
            return "Contains AI disclosure “\(phrase)”"
        }
        if generatorBearingNames.contains(compactKey), let token = generatorToken(in: probe) {
            return "Names AI generator “\(token)”"
        }
        return nil
    }

    static func generatorToken(in text: String) -> String? {
        guard let regex = generatorRegex else { return nil }
        let range = NSRange(text.startIndex..., in: text)
        guard let match = regex.firstMatch(in: text, range: range), let r = Range(match.range, in: text) else { return nil }
        return String(text[r])
    }

    /// True when the entry belongs to C2PA / Content Credentials.
    static func isC2PA(group: String, name: String, value: String) -> Bool {
        let g = group.lowercased()
        if g.hasPrefix("jumbf") || g.contains("c2pa") || g.hasPrefix("cbor") { return true }
        if name.localizedCaseInsensitiveContains("c2pa") { return true }
        if name.caseInsensitiveCompare("Provenance") == .orderedSame,
           value.localizedCaseInsensitiveContains("jumbf") || cloudManifestHosts.contains(where: value.contains) {
            return true
        }
        return false
    }
}

extension Data {
    /// Finds the first of `needles` inside this data, returning it as text.
    nonisolated func firstMarker(of needles: [Data]) -> String? {
        for needle in needles where range(of: needle) != nil {
            return String(decoding: needle, as: UTF8.self)
        }
        return nil
    }
}
